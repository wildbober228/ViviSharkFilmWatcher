export function iconSvg(name: string): string {
  return `<svg viewBox="0 0 24 24" aria-hidden="true">${PATHS[name] ?? ''}</svg>`;
}

export function setIcon(el: Element, name: string): void {
  let holder = el.querySelector(':scope > .ic');
  if (!holder) {
    holder = el.ownerDocument.createElement('span');
    holder.className = 'ic';
    el.prepend(holder);
  }
  if (holder.getAttribute('data-name') === name) return;
  holder.setAttribute('data-name', name);
  holder.innerHTML = iconSvg(name);
}

export function paintIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-icon]').forEach((el) => setIcon(el, el.dataset.icon!));
}
